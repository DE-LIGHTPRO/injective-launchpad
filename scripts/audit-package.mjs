/**
 * The package an auditor needs, built from the repository as it stands.
 *
 *   node scripts/audit-package.mjs
 *
 * WHY. `docs/AUDIT_SCOPE.md` says to send it "with a pinned commit hash and the wasm
 * checksums that scripts/build-wasm.sh produces at that commit". Collecting those by
 * hand is the kind of small friction that keeps the single most important mainnet
 * item sitting at the bottom of a list for weeks, so this does it in one command and
 * writes a document that can be sent as it is.
 *
 * IT REFUSES ON A DIRTY TREE. A commit hash that does not describe the bytes being
 * audited is worse than no hash: the auditor reviews one thing and a different thing
 * ships, and nobody finds out until it matters. The whole value of the package is
 * that the hash and the checksums agree.
 *
 * It writes docs/AUDIT-PACKAGE.md and prints nothing secret.
 */
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const ARTIFACTS = join(ROOT, 'target', 'wasm32-unknown-unknown', 'release');
const OUT = join(ROOT, 'docs', 'AUDIT-PACKAGE.md');

const sh = (cmd) => execSync(cmd, { cwd: ROOT, encoding: 'utf8' }).trim();

function die(msg, hint) {
  console.error(`\n  ✗ ${msg}`);
  if (hint) console.error(`    ${hint}\n`);
  process.exit(1);
}

// ------------------------------------------------------------- the commit --

const dirty = sh('git status --porcelain');
if (dirty) {
  die(
    'The working tree has uncommitted changes.',
    'A commit hash that does not describe the audited bytes is worse than none.\n    Commit first, then re-run.',
  );
}

const commit = sh('git rev-parse HEAD');
const shortCommit = commit.slice(0, 12);
const branch = sh('git rev-parse --abbrev-ref HEAD');
const committedAt = sh('git show -s --format=%cI HEAD');
const remote = sh('git remote get-url origin 2>/dev/null || echo "(no remote)"').replace(
  /\.git$/,
  '',
);

// -------------------------------------------------------------- the bytes --

/*
 * The checksums an auditor reproduces. `build-wasm.sh` pins the toolchain and the
 * target features precisely so these are reproducible; if they do not match at the
 * same commit, that disagreement is itself a finding and the auditor should say so
 * rather than proceed.
 */
const wasm = [];
for (const name of ['curve.wasm', 'factory.wasm']) {
  const path = join(ARTIFACTS, name);
  if (!existsSync(path)) {
    die(`Missing ${name}.`, 'Build first: ./scripts/build-wasm.sh');
  }
  const bytes = readFileSync(path);
  wasm.push({
    name,
    bytes: bytes.length,
    sha256: createHash('sha256').update(bytes).digest('hex'),
    builtAt: statSync(path).mtime.toISOString(),
  });
}

// --------------------------------------------------------------- the scope --

/** Lines of Rust in a path, so the auditor can size the engagement. */
function rustLines(glob) {
  try {
    return Number(sh(`find ${glob} -name '*.rs' -print0 | xargs -0 cat | wc -l`));
  } catch {
    return 0;
  }
}

const scope = [
  ['packages/launchpad-math/src', 'Bonding-curve and pool maths'],
  ['contracts/curve/src', 'One launch: curve, graduation, locked pool, fees'],
  ['contracts/factory/src', 'Launch creation, fixed policy, quote allowlist, admin'],
].map(([path, what]) => ({ path, what, lines: rustLines(join(ROOT, path)) }));

/** Test counts, as evidence of what is already covered rather than as a claim. */
let rustTests = 'unknown';
try {
  const out = execSync('cargo test 2>&1', { cwd: ROOT, encoding: 'utf8' });
  rustTests = String(
    [...out.matchAll(/test result: ok\. (\d+) passed/g)].reduce((n, m) => n + Number(m[1]), 0),
  );
} catch {
  rustTests = 'could not be run';
}

// ------------------------------------------------------------- the document --

const toolchain = existsSync(join(ROOT, 'rust-toolchain.toml'))
  ? readFileSync(join(ROOT, 'rust-toolchain.toml'), 'utf8').trim()
  : '(none pinned)';

const doc = `# Audit package

Generated by \`scripts/audit-package.mjs\`. Everything here describes one commit; if
the checksums below do not reproduce at that commit, stop and say so rather than
proceeding, because the disagreement is itself the finding.

## The commit

| | |
|---|---|
| repository | ${remote} |
| commit | \`${commit}\` |
| branch | ${branch} |
| committed | ${committedAt} |
| working tree | clean at generation |

\`\`\`bash
git clone ${remote}.git && cd ${remote.split('/').pop()}
git checkout ${shortCommit}
\`\`\`

## The bytes

Built with \`./scripts/build-wasm.sh\`, which pins the toolchain and the target
features. One crate per invocation: the combined form fails to link, because cargo
unifies the \`library\` feature and the factory ends up carrying curve's entry points.

| module | bytes | sha256 |
|---|---|---|
${wasm.map((w) => `| \`${w.name}\` | ${w.bytes.toLocaleString('en-US')} | \`${w.sha256}\` |`).join('\n')}

Toolchain:

\`\`\`
${toolchain}
\`\`\`

The wasm must carry no post-MVP instructions. Injective's wasmvm rejects the whole
module with a byte offset rather than a build flag, so \`build-wasm.sh\` checks it and
\`scripts/check-wasm-features.py\` is the check.

## Scope

| path | lines | what it is |
|---|---|---|
${scope.map((s) => `| \`${s.path}\` | ~${s.lines.toLocaleString('en-US')} | ${s.what} |`).join('\n')}

\`docs/AUDIT_SCOPE.md\` is the fuller statement, including what is deliberately out of
scope and why.

## What already exists

- **${rustTests} contract tests** passing at this commit, in cw-multi-test.
- **An internal review log**, \`docs/AUDIT.md\`. It opens with "Not a third-party
  audit" and is a record of defects found and fixed, including the reasoning. It is
  offered as context on where this codebase has historically been wrong, not as
  assurance.
- **A live testnet deployment** with an 8-step lifecycle script,
  \`scripts/e2e-testnet.mjs\`, covering creation, trading, graduation, the locked
  pool, exact accounting and the fee split, run against the deployed bytes.

## What the team already believes is risky

Stated so the engagement starts from candour rather than from discovery. None of
these is a known bug; they are the places where an error would hurt most.

- **Graduation is atomic and irreversible.** It moves the curve's reserve into a pool
  inside the same contract, in the same transaction as the buy that triggers it. A
  launch has no upgrade key, so a defect here is permanent for that launch.
- **The funds check on \`create_launch\` is exact and hand-written**, and now has to
  separate a launch fee from an opening buy that may share a denom, because the bank
  module merges same-denom coins before the contract sees them.
- **The factory has a wasm admin.** It cannot reach an existing launch, but it can
  change where future fees go and which curve code new launches run.
- **Fee accounting accrues and is paid by a permissionless \`claim_fees\`.** The
  arithmetic that splits it 70/30 and the invariant that the contract holds exactly
  pool plus owed fees are the things worth attacking.
- **The curve maths is integer-only and rounds deliberately.** Rounding that favours
  the contract over the trader, or the reverse, is a finding.

## Contact

Reach the maintainer through the repository.
`;

writeFileSync(OUT, doc);

console.log(`\n  commit  ${shortCommit} (${branch}, clean)`);
for (const w of wasm) console.log(`  ${w.name.padEnd(13)} ${w.sha256.slice(0, 16)}…  ${w.bytes.toLocaleString('en-US')} bytes`);
console.log(`  contract tests ${rustTests}`);
console.log(`\n  ✓ written to docs/AUDIT-PACKAGE.md\n`);
